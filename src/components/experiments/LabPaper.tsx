type PaperShape = keyof typeof paperEdges;
type Point = readonly [number, number];

// Small, alternating nicks on each hand-drawn outline reveal the backing fibers.
function tornOutline(points: readonly Point[], shape: PaperShape) {
  const detail = ["masthead", "black", "rust", "backing", "corner", "label"].includes(shape) ? 5 : 10;
  const outline = points.flatMap(([x, y], index) => {
    const [nextX, nextY] = points[(index + 1) % points.length];
    const dx = nextX - x;
    const dy = nextY - y;
    return Array.from({ length: detail }, (_, step) => {
      const fraction = step / detail;
      const sample = index * detail + step;
      const nick = step === 0 ? 0 : Math.sin(sample * 2.77) * .6 + Math.sin(sample * 4.21) * .4;
      const edgeX = nick * Math.min(Math.abs(dy) * .075, 3.5);
      const edgeY = nick * Math.min(Math.abs(dx) * .12, 10);
      return `${(x + dx * fraction - edgeX).toFixed(1)} ${(y + dy * fraction + edgeY).toFixed(1)}`;
    });
  });
  return `M${outline.join("L")}Z`;
}

export function LabPaperMasks() {
  return (
    <svg className="lab-mask-library" width="0" height="0" aria-hidden="true">
      <defs>
        <filter id="lab-ink-edge" x="-5%" y="-10%" width="110%" height="120%">
          <feTurbulence type="fractalNoise" baseFrequency=".31" numOctaves="2" seed="8" result="ink" />
          <feDisplacementMap in="SourceGraphic" in2="ink" scale="2.4" xChannelSelector="R" yChannelSelector="G" />
        </filter>
        {(Object.keys(paperEdges) as PaperShape[]).map((shape) => (
          <clipPath key={shape} id={`lab-edge-${shape}`} clipPathUnits="objectBoundingBox">
            <path transform="scale(.001)" d={tornOutline(paperEdges[shape], shape)} />
          </clipPath>
        ))}
      </defs>
    </svg>
  );
}

export function LabPaper({ shape, className = "" }: { shape: PaperShape; className?: string }) {
  const edge = { clipPath: `url(#lab-edge-${shape})` };
  return (
    <span className={`lab-paper ${className}`} aria-hidden="true">
      <span className="lab-paper-fiber" style={edge} />
      <span className="lab-paper-face" style={edge} />
    </span>
  );
}

export function LabSheet({ shape, className, children }: { shape: PaperShape; className: string; children: ReactNode }) {
  return (
    <div className={className}>
      <LabPaper shape={shape} />
      {children}
    </div>
  );
}
