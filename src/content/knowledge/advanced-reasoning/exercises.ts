export const allocationExercise = [
  "// 保存为 colors.mjs，再运行 node colors.mjs。",
  "import assert from \"node:assert/strict\";",
  "",
  "function allocate(nodes, edges, k) {",
  "  const stack = [], remaining = new Set(nodes), assigned = new Map(), spilled = [];",
  "  const neighbors = x => edges.flatMap(([a, b]) => a === x ? [b] : b === x ? [a] : []);",
  "  while (remaining.size > 0) {",
  "    const available = [...remaining];",
  "    const next = available.find(x => neighbors(x).filter(y => remaining.has(y)).length < k) ?? available[0];",
  "    remaining.delete(next);",
  "    stack.push(next);",
  "  }",
  "  while (stack.length > 0) {",
  "    const next = stack.pop();",
  "    const blocked = new Set(neighbors(next).map(x => assigned.get(x)));",
  "    const color = Array.from({ length: k }, (_, i) => i).find(c => !blocked.has(c));",
  "    if (color === undefined) spilled.push(next);",
  "    else assigned.set(next, color);",
  "  }",
  "  assert(edges.every(([a, b]) => !assigned.has(a) || !assigned.has(b) || assigned.get(a) !== assigned.get(b)));",
  "  return { registers: Object.fromEntries(assigned), spilled };",
  "}",
  "const path = [[\"a\", \"b\"], [\"b\", \"c\"]], triangle = [...path, [\"c\", \"a\"]];",
  "assert.equal(allocate([\"a\", \"b\", \"c\"], path, 2).spilled.length, 0);",
  "assert.equal(allocate([\"a\", \"b\", \"c\"], triangle, 2).spilled.length, 1);",
  "console.log(allocate([\"a\", \"b\", \"c\"], triangle, 2));",
  "// 输出只选溢出候选。实际改写须为其加入栈槽、载入和存储，再做分配。",
].join("\n");

