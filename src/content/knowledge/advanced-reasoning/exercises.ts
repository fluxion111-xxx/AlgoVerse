  "  # body -> header: update s using the old i, then advance i",
  "  addl %edx, %eax",
  "  addl $1, %edx",
  "  jmp .Lhead",
  ".Lexit:",
  "  ret",
  "# 在同目录保存 driver.c，内容见知识点正文。",
