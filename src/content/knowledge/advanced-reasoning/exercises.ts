export const vertexCoverExercise = [
  "// 保存为 cover.mjs，再运行 node cover.mjs。",
  "import assert from \"node:assert/strict\";",
  "",
  "function cover(n, edges) {",
  "  const picked = new Set();",
  "  for (const [a, b] of edges) {",
  "    if (picked.has(a) || picked.has(b)) continue;",
  "    picked.add(a);",
  "    picked.add(b);",
  "  }",
  "  const covers = mask => edges.every(([a, b]) => (mask & (1 << a | 1 << b)) !== 0);",
  "  let optimum = n;",
  "  for (let mask = 0; mask < 1 << n; mask++) {",
  "    if (covers(mask)) optimum = Math.min(optimum, mask.toString(2).replaceAll(\"0\", \"\").length);",
  "  }",
  "  assert(edges.every(([a, b]) => picked.has(a) || picked.has(b)));",
  "  assert(picked.size <= 2 * optimum);",
  "  return [picked.size, optimum];",
  "}",
  "",
  "const path = [[0, 1], [1, 2], [2, 3]];",
  "assert.deepEqual(cover(4, path), [4, 2]);",
  "for (let n = 1; n <= 5; n++) {",
  "  const possible = [];",
  "  for (let a = 0; a < n; a++) for (let b = a + 1; b < n; b++) possible.push([a, b]);",
  "  for (let graph = 0; graph < 1 << possible.length; graph++) {",
  "    cover(n, possible.filter((_, i) => (graph & (1 << i)) !== 0));",
  "  }",
  "}",
  "console.log(\"4-node path: [cover, optimum] = \", cover(4, path));",
].join("\n");

export const ctmcExercise = [
  "// 保存为 ctmc.mjs，再运行 node ctmc.mjs。",
  "import assert from \"node:assert/strict\";",
  "",
  "const a = 2, b = 1, t = 1;",
  "const rate = Math.max(a, b);",
  "const lambda = rate * t;",
  "let inA = 1;",
  "const K = 14;",
  "let weight = Math.exp(-lambda), estimate = weight;",
  "for (let k = 1; k <= K; k++) {",
  "  inA = inA * (1 - a / rate) + (1 - inA) * b / rate;",
  "  weight *= lambda / k;",
  "  estimate += weight * inA;",
  "}",
  "const exact = b / (a + b) + a / (a + b) * Math.exp(-(a + b) * t);",
  "// 泊松项的后续比值不超过 lambda/(K+2)。用几何级数给尾部上界。",
  "const tailUpperBound = (weight * lambda / (K + 1)) / (1 - lambda / (K + 2));",
  "// 另给浮点累加留 1e-14 的余量。",
  "assert(Math.abs(exact - estimate) <= tailUpperBound + 1e-14);",
  "console.log({ estimate, exact, tailUpperBound });",
].join("\n");

export const optimizationExercise = [
  "// 保存为 stop.mjs，再运行 node stop.mjs。",
  "import assert from \"node:assert/strict\";",
  "",
  "function step(mu, alpha, initial, iterations) {",
  "  let x = initial;",
  "  for (let k = 0; k < iterations; k++) x -= alpha * mu * x;",
  "  const gradient = mu * x;",
  "  return { x, nextStep: Math.abs(alpha * gradient),",
  "    residual: Math.abs(gradient), gap: mu * x * x / 2, bound: gradient ** 2 / (2 * mu) };",
  "}",
  "const normal = step(1, 0.5, 1, 3);",
  "const tinyStep = step(1, 1e-12, 1, 3);",
  "const flat = step(1e-6, 0.5, 10, 3);",
  "assert.equal(normal.x, 1 / 8);",
  "assert.equal(normal.gap, normal.bound);",
  "assert(tinyStep.nextStep < 1e-10 && tinyStep.gap > 0.49);",
  "assert(flat.residual < 2e-5 && flat.x > 9.9);",
  "console.table({ normal, tinyStep, flat });",
].join("\n");

