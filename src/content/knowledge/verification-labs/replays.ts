  "def frequencies(a,b):",
  "    t=np.r_[a,imu[(imu[:,0]>a)&(imu[:,0]<b),0],b]",
  "    xy=np.array([np.interp(t,imu[:,0],imu[:,k]) for k in range(1,7)]).T",
  "    return np.diff(t), (xy[1:]+xy[:-1])*.5",
  "def propagate(r,a,b,bias):",
  "    # Rotate specific force into the first camera frame before averaging.",
  "    dt, measurements = frequencies(a,b)",
  "    force=np.zeros(3)",
  "    for h, m in zip(dt,measurements):",
  "        half=Rotation.from_rotvec((m[3:]-bias)*h*.5)",
  "        force+=h*(r*half).apply(m[:3])",
  "        r=r*half*half",
  "    return r, force/(b-a)",
