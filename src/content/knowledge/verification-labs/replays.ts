  "         reprojectionError=2.,confidence=.99,flags=cv2.SOLVEPNP_ITERATIVE)",
  "    if not valid or len(inliers)<12: return None",
  "    pose=Rotation.from_rotvec(rv.ravel()).inv()",
  "    pos=-pose.apply(tv.ravel())",
  "    return (pose,pos) if np.linalg.norm(pos)<3 and pose.magnitude()<1.4 else None",
