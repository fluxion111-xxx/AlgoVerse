export const particleExercise = [
  "// 保存为 particles.mjs，再运行 node particles.mjs。",
  "import assert from \"node:assert/strict\";",
  "",
  "const observations = [1,0,1,1,0,1], n = 10000;",
  "const likelihood = (state,o) => o ? (state ? 0.9 : 0.1) : (state ? 0.1 : 0.9);",
  "for (let seed of [9,201,789]) {",
  "  const initialSeed = seed;",
  "  const rand = () => (seed = (Math.imul(seed,1664525)+1013904223)>>>0)/2**32;",
  "  let particles = Array.from({length:n}, () => Number(rand()<0.2));",
  "  let weights = Array(n).fill(1/n), exact = 0.2, maxError = 0, rounds = 0;",
  "  for (const o of observations) {",
  "    const predicted = 0.1*(1-exact)+0.7*exact;",
  "    exact = predicted*likelihood(1,o)/(predicted*likelihood(1,o)+(1-predicted)*likelihood(0,o));",
  "    particles = particles.map(state => Number(rand()<(state ? 0.7 : 0.1)));",
  "    weights = weights.map((w,i) => w*likelihood(particles[i],o));",
  "    const total = weights.reduce((sum,w) => sum+w, 0);",
  "    weights = weights.map(w => w/total);",
  "    const estimate = weights.reduce((sum,w,i) => sum+w*particles[i], 0);",
  "    maxError = Math.max(maxError,Math.abs(estimate-exact));",
  "    const ess = 1/weights.reduce((sum,w) => sum+w*w,0);",
  "    if (ess < n/2) {",
  "      let j = 0, cdf = weights[0];",
  "      const offset = rand()/n;",
  "      particles = particles.map((_,i) => {",
  "        const u = offset + i/n;",
  "        while (u >= cdf && j < n-1) cdf += weights[++j];",
  "        return particles[j];",
  "      });",
  "      weights.fill(1/n);",
  "      rounds++;",
  "    }",
  "  }",
  "  assert(maxError < 0.04 && rounds > 0);",
  "  console.log({ initialSeed, maxError, rounds, exact });",
  "}",
].join("\n");
