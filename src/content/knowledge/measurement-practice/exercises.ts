  "*/",
  "#include <mpi.h>",
  "#include <stdlib.h>",
  "#include <stdio.h>",
  "",
  "static int start(int rank, int ranks, int n) {",
  "    int remainder = n % ranks;",
  "    return rank * (n / ranks) + (rank < remainder ? rank : remainder);",
  "}",
  "",
  "int main(int argc, char **argv) {",
  "    MPI_Init(&argc, &argv);",
  "    int rank, ranks, n = 10;",
  "    MPI_Comm_rank(MPI_COMM_WORLD, &rank);",
  "    MPI_Comm_size(MPI_COMM_WORLD, &ranks);",
  "    if (rank == 0) {",
  "        if (argc > 2) n = -1;",
  "        if (argc == 2) {",
  "            char *end;",
  "            long parsed = strtol(argv[1], &end, 10);",
  "            n = end != argv[1] && *end == 0 && parsed >= 0 && parsed <= 100000 ? (int)parsed : -1;",
  "        }",
  "    }",
  "    MPI_Bcast(&n, 1, MPI_INT, 0, MPI_COMM_WORLD);",
  "    if (n < 0) {",
  "        if (rank == 0) fprintf(stderr, \"n must be an integer from 0 to 100000\\n\");",
  "        MPI_Finalize();",
  "        return 2;",
  "    }",
  "    long long local = 0, total = 0;",
  "    for (int i = start(rank, ranks, n); i < start(rank+1, ranks, n); ++i) local += i+1;",
  "    MPI_Allreduce(&local, &total, 1, MPI_LONG_LONG_INT, MPI_SUM, MPI_COMM_WORLD);",
  "    long long expected = (long long)n*(n+1)/2;",
  "    if (rank == 0) printf(\"%lld (expected %lld)\\n\", total, expected);",
  "    MPI_Finalize();",
  "    return total != expected;",
  "}",
