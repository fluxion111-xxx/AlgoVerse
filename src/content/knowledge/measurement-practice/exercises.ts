export const coverageExercise = [
  "// 保存为 coverage.mjs，运行 node coverage.mjs。",
  "import assert from \"node:assert/strict\";",
  "",
  "const n = 20, z = 1.959963984540054;",
  "const wald = k => {",
  "  const p = k / n, half = z * Math.sqrt(p * (1-p) / n);",
  "  return [Math.max(0, p-half), Math.min(1, p+half)];",
  "};",
  "const wilson = k => {",
  "  const p = k / n, denominator = 1 + z*z/n;",
  "  const center = (p + z*z/(2*n)) / denominator;",
  "  const half = z * Math.sqrt(p*(1-p)/n + z*z/(4*n*n)) / denominator;",
  "  return [Math.max(0, center-half), Math.min(1, center+half)];",
  "};",
  "const includes = ([lo, hi], p) => lo <= p && p <= hi;",
  "function exact(p, interval) {",
  "  let mass = (1-p)**n, covered = 0, meanWidth = 0;",
  "  for (let k = 0; k <= n; k++) {",
  "    const bounds = interval(k);",
  "    if (includes(bounds, p)) covered += mass;",
  "    meanWidth += mass * (bounds[1] - bounds[0]);",
  "    if (k < n) mass *= (n-k)/(k+1) * p/(1-p);",
  "  }",
  "  return { covered, meanWidth };",
  "}",
  "let seed = 589;",
  "const random = () => (seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 2**32;",
  "for (const p of [0.05, 0.2, 0.5, 0.95]) {",
  "  let w = 0, s = 0;",
  "  const runs = 20000;",
  "  for (let i = 0; i < runs; i++) {",
  "    let k = 0;",
  "    for (let j = 0; j < n; j++) if (random() < p) k++;",
  "    w += Number(includes(wald(k), p));",
  "    s += Number(includes(wilson(k), p));",
  "  }",
  "  const exactWald = exact(p, wald), exactWilson = exact(p, wilson);",
  "  assert(Math.abs(w/runs - exactWald.covered) < 0.02);",
  "  assert(Math.abs(s/runs - exactWilson.covered) < 0.02);",
  "  console.log({ p, exactWald, exactWilson, simulatedWald: w/runs, simulatedWilson: s/runs });",
  "}",
].join("\n");

