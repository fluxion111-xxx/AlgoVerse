// The lesson displays this text for running in an isolated Linux environment.
export const captureExercise = [
  "#!/usr/bin/env bash",
  "set -euo pipefail",
  "# Run in an isolated Linux VM as root; requires ip, tcpdump, curl and Python 3.",
  "out=$(mktemp -d \"${TMPDIR:-/tmp}/algoverse-v6.XXXXXX\")",
  "suffix=${out##*.}",
  "client=\"avc-${suffix}\"",
  "server=\"avs-${suffix}\"",
  "cpid=",
  "spid=",
  "http_pid=",
  "",
  "cleanup() {",
  "  for pid in \"$cpid\" \"$spid\" \"$http_pid\"; do",
  "    if [ -n \"$pid\" ]; then",
  "      kill \"$pid\" 2>/dev/null || true",
  "      wait \"$pid\" 2>/dev/null || true",
  "    fi",
  "  done",
  "  ip netns del \"$client\" 2>/dev/null || true",
  "  ip netns del \"$server\" 2>/dev/null || true",
  "}",
  "trap cleanup EXIT",
  "",
  "ip netns add \"$client\"",
  "ip netns add \"$server\"",
  "ip -n \"$client\" link add av-c type veth peer name av-s netns \"$server\"",
  "ip -n \"$client\" link set lo up",
  "ip -n \"$server\" link set lo up",
  "ip -n \"$client\" -6 addr add fd42::1/64 dev av-c nodad",
  "ip -n \"$server\" -6 addr add fd42::2/64 dev av-s nodad",
  "ip -n \"$client\" link set av-c up",
  "ip -n \"$server\" link set av-s up",
  "mkdir \"$out/www\"",
  "printf 'algoverse-v6\\n' > \"$out/www/index.html\"",
  "",
  "ip netns exec \"$server\" python3 -m http.server 18080 --bind fd42::2 --directory \"$out/www\" > \"$out/http.log\" 2>&1 &",
  "http_pid=$!",
  "# Readiness connects only inside the server namespace.",
  "for tick in {1..50}; do",
  "  if ip netns exec \"$server\" curl -g -6 --noproxy '*' -fsS --max-time 1 'http://[fd42::2]:18080/' >/dev/null 2>&1; then",
  "    break",
  "  fi",
  "  if [ \"$tick\" -eq 50 ]; then exit 1; fi",
  "  sleep 0.1",
  "done",
  "",
  "ip netns exec \"$client\" env LC_ALL=C tcpdump -U -n -i av-c -w \"$out/client.pcap\" 'ip6 and tcp port 18080' 2> \"$out/client.log\" &",
  "cpid=$!",
  "ip netns exec \"$server\" env LC_ALL=C tcpdump -U -n -i av-s -w \"$out/server.pcap\" 'ip6 and tcp port 18080' 2> \"$out/server.log\" &",
  "spid=$!",
  "for tick in {1..50}; do",
  "  if grep -q 'listening on' \"$out/client.log\" && grep -q 'listening on' \"$out/server.log\"; then",
  "    break",
  "  fi",
  "  if [ \"$tick\" -eq 50 ]; then exit 1; fi",
  "  sleep 0.1",
  "done",
  "ip netns exec \"$client\" curl -g -6 --noproxy '*' -fsS --max-time 5 'http://[fd42::2]:18080/' > \"$out/body.txt\"",
  "grep -qx 'algoverse-v6' \"$out/body.txt\"",
  "kill -INT \"$cpid\" \"$spid\"",
  "wait \"$cpid\" || true",
  "wait \"$spid\" || true",
  "cpid=",
  "spid=",
  "for side in client server; do",
  "  if command -v tshark >/dev/null; then",
  "    tshark -r \"$out/$side.pcap\" -Y 'tcp.port == 18080' -T fields \\",
  "      -e ipv6.src -e ipv6.dst -e tcp.srcport -e tcp.dstport \\",
  "      -e tcp.seq_raw -e tcp.ack_raw -e tcp.flags -e tcp.len > \"$out/$side.tsv\"",
  "  else",
  "    tcpdump -n -S -r \"$out/$side.pcap\" > \"$out/$side.txt\"",
  "  fi",
  "done",
  "printf 'Capture files: %s\\n' \"$out\"",
].join("\n");
