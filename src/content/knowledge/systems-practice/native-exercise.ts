// Shown as copyable teaching content. The website never executes this program.
export const nativeExercise = [
  "import { mkdirSync, readFileSync, writeFileSync } from \"node:fs\";",
  "import { join } from \"node:path\";",
  "",
  "const [, , input, output, abi = \"win64\"] = process.argv;",
  "if (!input || !output || ![\"win64\", \"sysv\"].includes(abi)) {",
  "  throw new Error(\"Usage: node compile.mjs source.expr new-output-dir win64|sysv\");",
  "}",
  "",
  "function tokenize(source) {",
  "  const tokens = [];",
  "  const pattern = /\\s+|[a-zA-Z_][a-zA-Z_0-9]*|\\d+|[()+*\\-<]/y;",
  "  let pos = 0;",
  "  while (pos < source.length) {",
  "    pattern.lastIndex = pos;",
  "    const value = pattern.exec(source)?.[0];",
  "    if (!value) throw new Error(\"Unexpected character at offset \" + pos);",
  "    if (!/^\\s/.test(value)) {",
  "      const keyword = [\"if\", \"then\", \"else\"].includes(value);",
  "      const kind = /^\\d/.test(value) ? \"number\" : !keyword && /^[a-zA-Z_]/.test(value) ? \"name\" : value;",
  "      tokens.push({ kind, value, pos });",
  "    }",
  "    pos += value.length;",
  "  }",
  "  tokens.push({ kind: \"eof\", pos });",
  "  return tokens;",
  "}",
  "",
  "function parse(tokens) {",
  "  let i = 0;",
  "  const peek = () => tokens[i];",
  "  function take(kind) {",
  "    const token = peek();",
  "    if (token.kind !== kind) throw new Error(\"Expected \" + kind + \" at offset \" + token.pos);",
  "    i++;",
  "    return token;",
  "  }",
  "  function atom() {",
  "    const token = peek();",
  "    if (token.kind === \"(\") {",
  "      take(\"(\");",
  "      const value = sum();",
  "      take(\")\");",
  "      return value;",
  "    }",
  "    if (token.kind === \"name\") return { kind: \"name\", ...take(\"name\") };",
  "    const number = take(\"number\");",
  "    return { kind: \"int\", value: Number(number.value), pos: number.pos };",
  "  }",
  "  function chain(read, operators) {",
  "    let left = read();",
  "    while (operators.includes(peek().kind)) {",
  "      const operator = take(peek().kind);",
  "      left = { kind: operator.kind, left, right: read(), pos: operator.pos };",
  "    }",
  "    return left;",
  "  }",
  "  const product = () => chain(atom, [\"*\"]);",
  "  const sum = () => chain(product, [\"+\", \"-\"]);",
  "  take(\"if\");",
  "  const left = sum();",
  "  const cmp = take(\"<\");",
  "  const right = sum();",
  "  take(\"then\");",
  "  const yes = sum();",
  "  take(\"else\");",
  "  const no = sum();",
  "  take(\"eof\");",
  "  return { kind: \"if\", test: { kind: \"<\", left, right, pos: cmp.pos }, yes, no };",
  "}",
  "",
  "function typeOf(node) {",
  "  switch (node.kind) {",
  "    case \"name\":",
  "      if (node.value !== \"n\") throw new Error(\"Unknown name at offset \" + node.pos);",
  "      return \"int\";",
  "    case \"int\":",
  "      if (!Number.isInteger(node.value) || node.value > 2147483647) {",
  "        throw new Error(\"Literal outside signed 32-bit range at offset \" + node.pos);",
  "      }",
  "      return \"int\";",
  "    case \"if\":",
  "      if (typeOf(node.test) !== \"bool\" || typeOf(node.yes) !== \"int\" || typeOf(node.no) !== \"int\") {",
  "        throw new Error(\"Expected a Boolean test and two integer branches\");",
  "      }",
  "      return \"int\";",
  "    default:",
  "      if (typeOf(node.left) !== \"int\" || typeOf(node.right) !== \"int\") {",
  "        throw new Error(\"Expected integers at offset \" + node.pos);",
  "      }",
  "      return node.kind === \"<\" ? \"bool\" : \"int\";",
  "  }",
  "}",
  "",
  "function toSSA(tree) {",
  "  let next = 0;",
  "  const makeValue = () => \"%\" + next++;",
  "  function lower(node, instructions) {",
  "    if (node.kind === \"int\") return node.value;",
  "    if (node.kind === \"name\") return \"%arg\";",
  "    const left = lower(node.left, instructions), right = lower(node.right, instructions);",
  "    const dest = makeValue();",
  "    instructions.push({ op: node.kind, dest, left, right });",
  "    return dest;",
  "  }",
  "  const entry = [], yes = [], no = [];",
  "  const cond = lower(tree.test, entry), a = lower(tree.yes, yes), b = lower(tree.no, no);",
  "  const dest = makeValue();",
  "  return [",
  "    { label: \"entry\", body: entry, exit: { op: \"branch\", cond, yes: \"yes\", no: \"no\" } },",
  "    { label: \"yes\", body: yes, exit: { op: \"jump\", to: \"join\" } },",
  "    { label: \"no\", body: no, exit: { op: \"jump\", to: \"join\" } },",
  "    { label: \"join\", phi: { dest, inputs: { yes: a, no: b } }, body: [], exit: { op: \"return\", value: dest } },",
  "  ];",
  "}",
  "",
  "function toAssembly(blocks, abi) {",
  "  const slots = new Map([[\"%arg\", 0]]);",
  "  for (const block of blocks) {",
  "    for (const { dest } of block.body) slots.set(dest, 4 * slots.size);",
  "    if (block.phi) slots.set(block.phi.dest, 4 * slots.size);",
  "  }",
  "  const frame = Math.ceil((slots.size * 4 + 8) / 16) * 16 - 8;",
  "  const operand = value => typeof value === \"number\" ? \"$\" + value : slots.get(value) + \"(%rsp)\";",
  "  const label = name => \".L\" + name;",
  "  const win = abi === \"win64\";",
  "  const out = [\".text\", \".globl calc\", ...(win ? [\".seh_proc calc\"] : [\".type calc,@function\"]), \"calc:\", \"  subq $\" + frame + \", %rsp\"];",
  "  if (win) out.push(\".seh_stackalloc \" + frame, \".seh_endprologue\");",
  "  out.push(\"  movl \" + (win ? \"%ecx\" : \"%edi\") + \", \" + operand(\"%arg\"));",
  "  const opcodes = { \"+\": \"addl\", \"-\": \"subl\", \"*\": \"imull\" };",
  "  for (const block of blocks) {",
  "    out.push(label(block.label) + \":\");",
  "    for (const { op, dest, left, right } of block.body) {",
  "      out.push(\"  movl \" + operand(left) + \", %eax\");",
  "      if (op === \"<\") {",
  "        out.push(\"  cmpl \" + operand(right) + \", %eax\", \"  setl %al\", \"  movzbl %al, %eax\");",
  "      } else {",
  "        out.push(\"  \" + opcodes[op] + \" \" + operand(right) + \", %eax\");",
  "      }",
  "      out.push(\"  movl %eax, \" + operand(dest));",
  "    }",
  "    const exit = block.exit;",
  "    if (exit.op === \"branch\") {",
  "      out.push(\"  cmpl $0, \" + operand(exit.cond), \"  jne \" + label(exit.yes), \"  jmp \" + label(exit.no));",
  "    } else if (exit.op === \"jump\") {",
  "      const phi = blocks.find(item => item.label === exit.to)?.phi;",
  "      if (phi) out.push(\"  movl \" + operand(phi.inputs[block.label]) + \", %eax\", \"  movl %eax, \" + operand(phi.dest));",
  "      out.push(\"  jmp \" + label(exit.to));",
  "    } else {",
  "      out.push(\"  movl \" + operand(exit.value) + \", %eax\", \"  addq $\" + frame + \", %rsp\", \"  ret\");",
  "    }",
  "  }",
  "  out.push(...(win ? [\".seh_endproc\"] : [\".size calc,.-calc\", '.section .note.GNU-stack,\"\",@progbits']), \"\");",
  "  return out.join(\"\\n\");",
  "}",
  "",
  "const tree = parse(tokenize(readFileSync(input, \"utf8\")));",
  "typeOf(tree);",
  "const blocks = toSSA(tree);",
  "const assembly = toAssembly(blocks, abi);",
  "mkdirSync(output);",
  "for (const [name, data] of [",
  "  [\"ast.json\", JSON.stringify(tree, null, 2)],",
  "  [\"ssa.json\", JSON.stringify(blocks, null, 2)],",
  "  [\"calc.S\", assembly],",
  "  [\"driver.c\", '#include <stdio.h>\\nint calc(int n);\\nint main(void) {\\n  int tests[] = {-1, 2, 3, 4};\\n  for (int i = 0; i < 4; ++i) printf(\"%d\\\\n\", calc(tests[i]));\\n  return 0;\\n}\\n'],",
  "]) writeFileSync(join(output, name), data, { flag: \"wx\" });",
  "",
  "// 保存为 compile.mjs。另存 input.expr：if n < 3 then n + 1 else n * 3 + 2",
  "// Windows x86-64，使用 MinGW-w64：",
  "// node compile.mjs input.expr out win64",
  "// gcc -c out/calc.S -o out/calc.o",
  "// objdump -d out/calc.o",
  "// gcc out/calc.o out/driver.c -o out/run.exe",
  "// ./out/run.exe",
  "// Linux x86-64 使用 sysv，链接输出名可改为 out/run。",
].join("\n");
